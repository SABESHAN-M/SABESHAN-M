// ───────────────────────── DATA ─────────────────────────
async function fetchRepos() {
  const headers = { Accept: "application/vnd.github+json" };
  if (token) headers.Authorization = `Bearer ${token}`;

  const response = await axios.get(
    `https://api.github.com/users/${username}/repos`,
    { headers, params: { sort: "pushed", per_page: 30 } }
  );

  return response.data
    .filter((r) => !r.fork && !r.archived && !CONFIG.skipRepos.includes(r.name))
    .slice(0, CONFIG.maxProjects);
}

// ───────────────────────── BLOCKS ─────────────────────────
function generateProjectCards(repos) {
  if (!repos.length) return "_No public projects yet._";

  const cells = repos.map(
    (repo) => `
<td width="50%" align="center">
  <a href="${repo.html_url}">
    <img src="https://github-readme-stats.vercel.app/api/pin/?username=${username}&repo=${repo.name}&theme=tokyonight&bg_color=${CONFIG.bg}&border_color=${CONFIG.accent}&title_color=${CONFIG.accent}&icon_color=${CONFIG.accent}" />
  </a>
</td>`
  );

  // two cards per row
  const rows = [];
  for (let i = 0; i < cells.length; i += 2) {
    rows.push(`<tr>${cells[i]}${cells[i + 1] || "<td></td>"}\n</tr>`);
  }

  return `<table align="center" width="100%">\n${rows.join("\n")}\n</table>`;
}

